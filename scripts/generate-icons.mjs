#!/usr/bin/env node
/**
 * Generates React components from design/icons/mw-*.svg without changing the drawing
 * (CLAUDE.md: never redraw design SVGs). Run: `pnpm icons`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const source = 'design/icons';
const target = 'resources/js/components/mw/module-icons.generated.tsx';

const toPascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const toJsxAttrs = (attrs) => attrs.replace(/([a-z]+)-([a-z])/g, (_, a, b) => `${a}${b.toUpperCase()}`);

const files = readdirSync(source).filter((f) => /^mw-.*\.svg$/.test(f)).sort();
const entries = files.map((file) => {
    const svg = readFileSync(join(source, file), 'utf8').trim();
    const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
    const key = basename(file, '.svg').replace(/^mw-/, '');

    return { key, name: `${toPascal(key)}Icon`, inner: toJsxAttrs(inner) };
});

const out = `// Generated by scripts/generate-icons.mjs from design/icons — do not edit.
import { type SVGProps } from 'react';

type IconProps = SVGProps<SVGSVGElement> & { title?: string };

function Svg({ title, children, ...props }: IconProps & { children: React.ReactNode }) {
    return (
        <svg
            xmlns="http://www.w3.org/2000/svg"
            width={24}
            height={24}
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            strokeWidth={1.75}
            strokeLinecap="round"
            strokeLinejoin="round"
            aria-hidden={title ? undefined : true}
            role={title ? 'img' : undefined}
            {...props}
        >
            {title ? <title>{title}</title> : null}
            {children}
        </svg>
    );
}

${entries
    .map(
        ({ name, inner }) => `export function ${name}(props: IconProps) {
    return <Svg {...props}>${inner}</Svg>;
}`,
    )
    .join('\n\n')}

export const moduleIcons = {
${entries.map(({ key, name }) => `    '${key}': ${name},`).join('\n')}
} as const;

export type ModuleIconName = keyof typeof moduleIcons;
`;

writeFileSync(target, out);
console.log(`Generated ${entries.length} icons → ${target}`);
