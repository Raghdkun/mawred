#!/usr/bin/env bash
# Sets up the host's nginx in front of Mawred (ADR-0019, D134): HTTPS certificates from Let's
# Encrypt (certbot, webroot), a redirect from HTTP, and proxies to the containers' loopback ports.
# Run as root once .env.production exists, and again whenever a host name or deploy/nginx/ changes:
#
#   sudo /core/mawred/deploy/nginx-site.sh
#
# It writes only its own files (/etc/nginx/conf.d/mawred.conf, /etc/nginx/snippets/mawred-*.conf
# and a certbot renewal hook); other sites on this nginx are left alone. deploy.sh points the
# app upstream at the live blue/green slot through .deploy/nginx-upstream.conf.

set -Eeuo pipefail

root_dir="$(cd "$(dirname "$0")/.." && pwd)"
env_file="$root_dir/.env.production"
state_dir="$root_dir/.deploy"
site="/etc/nginx/conf.d/mawred.conf"
webroot="/var/www/letsencrypt"

log() { printf '== %s\n' "$*"; }
die() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

[ "$(id -u)" = 0 ] || die "run as root (sudo)"
[ -f "$env_file" ] || die "$env_file is missing (see deploy/env.production.example)"
command -v nginx >/dev/null || die "nginx is not installed (deploy/harden.sh installs it)"
command -v certbot >/dev/null || die "certbot is not installed (deploy/harden.sh installs it)"

env_get() {
    local line
    line="$(grep -E "^$1=" "$env_file" | tail -n 1 || true)"
    line="${line#*=}"
    line="${line%\"}"
    line="${line#\"}"
    printf '%s' "$line"
}

valid_host() { [[ "$1" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$ ]] || die "not a host name: $1"; }

app_host="$(env_get APP_HOST)"
port_or() {
    local port
    port="$(env_get "$1")"
    port="${port:-$2}"
    [[ "$port" =~ ^[0-9]{2,5}$ ]] || die "$1 is not a port: $port"
    printf '%s' "$port"
}
blue_port="$(port_or MAWRED_BLUE_PORT 8081)"
green_port="$(port_or MAWRED_GREEN_PORT 8082)"
reverb_port="$(port_or MAWRED_REVERB_PORT 8090)"
glitchtip_port="$(port_or MAWRED_GLITCHTIP_PORT 8070)"
careers_host="$(env_get CAREERS_HOST)"
glitchtip_host="$(env_get GLITCHTIP_HOST)"
acme_email="$(env_get ACME_EMAIL)"
[ -n "$app_host" ] || die "APP_HOST is not set in $env_file"
[ -n "$acme_email" ] || die "ACME_EMAIL is not set in $env_file (Let's Encrypt expiry notices)"
hosts=()
for host in "$app_host" "$careers_host" "$glitchtip_host"; do
    [ -z "$host" ] && continue
    valid_host "$host"
    hosts+=("$host")
done

has_cert() { [ -f "/etc/letsencrypt/live/$1/fullchain.pem" ]; }

# One HTTPS server block; $1 = host, $2 = upstream, $3 = body size, $4 = yes to route Reverb.
https_block() {
    has_cert "$1" || return 0
    cat <<CONF

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name $1;
    ssl_certificate /etc/letsencrypt/live/$1/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$1/privkey.pem;
    include snippets/mawred-site.conf;
    client_max_body_size $3;
CONF
    if [ "$4" = yes ]; then
        cat <<'CONF'

    # Browsers' WebSockets to Reverb; the app publishes to it over the Docker network.
    location ^~ /app/ {
        proxy_pass http://mawred_reverb;
        include snippets/mawred-websocket.conf;
    }
CONF
    fi
    cat <<CONF

    location / {
        proxy_pass http://$2;
        include snippets/mawred-proxy.conf;
    }
}
CONF
}

render() {
    cat <<CONF
# Generated by $root_dir/deploy/nginx-site.sh; run it again instead of editing this file.

upstream mawred_app {
    # The live blue/green app slot, written by deploy/deploy.sh (blue 127.0.0.1:$blue_port, green :$green_port).
    include $state_dir/nginx-upstream.conf;
    keepalive 32;
}

upstream mawred_reverb {
    server 127.0.0.1:$reverb_port;
}

upstream mawred_glitchtip {
    server 127.0.0.1:$glitchtip_port;
    keepalive 8;
}

map \$http_upgrade \$mawred_connection_upgrade {
    default upgrade;
    "" "";
}

server {
    listen 80;
    listen [::]:80;
    server_name ${hosts[*]};
    server_tokens off;

    location ^~ /.well-known/acme-challenge/ {
        root $webroot;
    }

    location / {
        return 301 https://\$host\$request_uri;
    }
}
CONF
    https_block "$app_host" mawred_app 25m yes
    [ -z "$careers_host" ] || https_block "$careers_host" mawred_app 25m no
    [ -z "$glitchtip_host" ] || https_block "$glitchtip_host" mawred_glitchtip 20m no
}

# Writes the config, tests it and reloads; a config nginx rejects is taken out again.
install_site() {
    local backup=""
    if [ -f "$site" ]; then
        backup="$(mktemp)"
        cp "$site" "$backup"
    fi
    render >"$site"
    if nginx -t -q; then
        systemctl reload nginx
        [ -z "$backup" ] || rm -f "$backup"
        return 0
    fi
    if [ -n "$backup" ]; then
        mv "$backup" "$site"
    else
        rm -f "$site"
    fi
    die "nginx rejected the generated config; the previous one is back in place"
}

log "snippets"
for snippet in "$root_dir"/deploy/nginx/mawred-*.conf; do
    install -m 644 "$snippet" "/etc/nginx/snippets/$(basename "$snippet")"
done
install -d -m 755 "$webroot"

if [ ! -f "$state_dir/nginx-upstream.conf" ]; then
    slot="$(cat "$state_dir/live-slot" 2>/dev/null || echo blue)"
    port="$blue_port"
    [ "$slot" = green ] && port="$green_port"
    owner="$(stat -c '%U:%G' "$root_dir")"
    install -d -o "${owner%%:*}" -g "${owner##*:}" "$state_dir"
    printf '# Written by deploy/deploy.sh: the live app slot (%s).\nserver 127.0.0.1:%s;\n' "$slot" "$port" >"$state_dir/nginx-upstream.conf"
    chown "$owner" "$state_dir/nginx-upstream.conf"
fi

log "HTTP site (answers Let's Encrypt, redirects everything else)"
install_site

for host in "${hosts[@]}"; do
    if ! has_cert "$host"; then
        log "certificate for $host"
        certbot certonly --webroot -w "$webroot" -d "$host" --cert-name "$host" \
            --email "$acme_email" --agree-tos --no-eff-email --non-interactive ||
            die "certbot could not get a certificate for $host: check its DNS record points here and port 80 is open"
    fi
done

log "renewals reload nginx"
install -d /etc/letsencrypt/renewal-hooks/deploy
printf '#!/bin/sh\n# Installed by deploy/nginx-site.sh.\nsystemctl reload nginx\n' >/etc/letsencrypt/renewal-hooks/deploy/mawred-reload-nginx.sh
chmod 755 /etc/letsencrypt/renewal-hooks/deploy/mawred-reload-nginx.sh

log "HTTPS site for ${hosts[*]}"
install_site
log "done: https://$app_host/health/ready should answer once deploy.sh init has run"
